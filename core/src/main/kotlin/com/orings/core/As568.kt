            0.926, 0.989, 1.051, 1.114, 1.176, 1.239, 1.301, 1.364, // -021 ~ -028
        )
        step(29, 41, 0.070, 1.489, 0.125)
        step(42, 50, 0.070, 3.239, 0.25)

        // ---- 1xx（CS 0.103）----
        list(
