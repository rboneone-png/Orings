package com.orings.core

import kotlin.math.round

/**
 * AS568 標準尺寸表（-001 ~ -475，以及 -901 ~ -932 直螺紋接頭用）。
 *
 * 原始資料為英吋，[StandardSize.innerDiameter]/[StandardSize.crossSection] 為換算後的 mm。
 * 等差區段用 [step] 產生，不規則區段逐一列出。
 * 注意：數值依標準整理，正式使用前請與 SAE AS568 原文或廠商型錄核對。
 */
object As568 {
    private const val INCH = 25.4

    private class Builder {
        val out = mutableListOf<StandardSize>()

        fun add(dash: Int, idInch: Double, csInch: Double) {
            out += StandardSize(
                standard = Standard.AS568,
                code = "-%03d".format(dash),
                innerDiameter = idInch * INCH,
                crossSection = csInch * INCH,
                idInch = idInch,
                csInch = csInch,
            )
        }

        /** 逐一列出：從 [firstDash] 開始，依序對應 [ids] */
        fun list(firstDash: Int, csInch: Double, vararg ids: Double) {
            ids.forEachIndexed { i, id -> add(firstDash + i, id, csInch) }
        }

        /** 等差：[firstDash]..[lastDash]，內徑從 [startId] 每號增加 [step] */
        fun step(firstDash: Int, lastDash: Int, csInch: Double, startId: Double, step: Double) {
            for (dash in firstDash..lastDash) {
                val id = startId + (dash - firstDash) * step
                add(dash, round(id * 1000) / 1000, csInch)
            }
        }
    }

    val sizes: List<StandardSize> = Builder().apply {
