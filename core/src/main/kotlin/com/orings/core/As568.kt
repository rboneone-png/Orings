        // ---- 2xx（CS 0.139）----
        list(
            201, 0.139,
            0.171, 0.234, 0.296, 0.359, 0.421, 0.484, 0.546, 0.609, 0.671, 0.734, // -201 ~ -210
            0.796, 0.859, 0.921, 0.984, 1.046, 1.109, 1.171, 1.234, 1.296, 1.359, // -211 ~ -220
            1.421, 1.484, // -221, -222
        )
        step(223, 258, 0.139, 1.609, 0.125)
        step(259, 262, 0.139, 6.234, 0.25)
        step(263, 274, 0.139, 7.484, 0.5)
        step(275, 281, 0.139, 13.984, 1.0)
