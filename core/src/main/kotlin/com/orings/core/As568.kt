            0.362, 0.424, 0.487, 0.549, 0.612, 0.674, 0.737, 0.799, 0.862, 0.924, // -110 ~ -119
            0.987, 1.049, 1.112, 1.174, 1.237, 1.299, 1.362, 1.424, 1.487, 1.549, // -120 ~ -129
            1.612, 1.674, 1.737, 1.799, 1.862, 1.925, 1.987, 2.050, 2.112, 2.175, // -130 ~ -139
            2.237, 2.300, 2.362, 2.425, 2.487, 2.550, 2.612, 2.675, 2.737, 2.800, // -140 ~ -149
